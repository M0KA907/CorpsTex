"""Prepare versioned local release files using existing tools and locked dependencies."""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import tarfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def version():
    value = json.loads((ROOT / 'src-tauri/tauri.conf.json').read_text())['version']
    if not re.fullmatch(r'\d+\.\d+\.\d+', value):
        raise ValueError('Use a numeric major.minor.patch release version.')
    package = json.loads((ROOT / 'package.json').read_text())['version']
    lock = json.loads((ROOT / 'package-lock.json').read_text())
    cargo = re.search(r'^version = "([^"]+)"', (ROOT / 'src-tauri/Cargo.toml').read_text(), re.M)[1]
    cargo_lock = re.search(r'\[\[package\]\]\nname = "corpstex"\nversion = "([^"]+)"', (ROOT / 'src-tauri/Cargo.lock').read_text())[1]
    if {value, package, cargo, cargo_lock, lock['version'], lock['packages']['']['version']} != {value}:
        raise ValueError('Application, npm lockfile and Cargo versions must match.')
    return value


def notices():
    entries = {}
    lock = json.loads((ROOT / 'package-lock.json').read_text())
    for path, info in lock['packages'].items():
        if not path or info.get('dev') or not (ROOT / path).is_dir():
            continue
        manifest = json.loads((ROOT / path / 'package.json').read_text())
        entries['npm ' + manifest['name'] + '@' + manifest['version']] = (
            ROOT / path, str(info.get('license', 'See bundled license')), None)
    for target in ['x86_64-unknown-linux-gnu']:
        metadata = json.loads(subprocess.check_output([
            'cargo', 'metadata', '--locked', '--manifest-path', str(ROOT / 'src-tauri/Cargo.toml'),
            '--filter-platform', target, '--format-version', '1'], cwd=ROOT))
        for package in metadata['packages']:
            if package['source'] is not None:
                entries['Cargo ' + package['name'] + '@' + package['version']] = (
                    Path(package['manifest_path']).parent, package['license'] or 'See bundled license', package['license_file'])
    output = ['CorpsTex third-party notices',
              'Includes locked Linux build and runtime dependencies; some entries may not be linked.',
              'Each component retains its own copyright and license. CorpsTex is GPL-3.0-only.',
              'Corresponding application source: the matching version tag in https://github.com/M0KA907/CorpsTex',
              'This file is generated by scripts/release.py notices.\n']
    for name, (directory, license_id, license_file) in sorted(entries.items()):
        files = {p for p in directory.iterdir() if p.is_file() and re.match(
            r'(?i)^(licen[cs]e|copying|notice|copyright|thirdpartynotices)([.\-_]|$)', p.name)}
        if license_file:
            path = (directory / license_file).resolve()
            if not path.is_relative_to(directory.resolve()):
                raise ValueError('License outside package: ' + name)
            files.add(path)
        if not files:
            # Some published crates omit the workspace-root license. Exact-version
            # upstream copies are reviewed locally; dependency upgrades fail closed.
            fallback = ROOT / 'packaging/licenses' / name.removeprefix('Cargo ').replace('@', '-') / 'LICENSE'
            if not fallback.is_file():
                raise ValueError('No license text found for ' + name)
            files.add(fallback)
        output.extend(['\n' + '=' * 72, name, 'Declared license: ' + license_id])
        for path in sorted(files):
            output.extend(['\n--- ' + path.name + ' ---', path.read_text(encoding='utf-8')])
    # Normalize only whitespace, retaining the full upstream license wording.
    text = '\n'.join(line.rstrip() for line in '\n'.join(output).splitlines()).rstrip() + '\n'
    (ROOT / 'NOTICE').write_text(text, encoding='utf-8')
    print('Wrote NOTICE for', len(entries), 'locked components')


def archive(binary, destination):
    release_version = version()
    destination.mkdir(parents=True, exist_ok=True)
    stage = destination / ('CorpsTex-' + release_version + '-' + 'linux-x86_64')
    stage.mkdir(exist_ok=False)
    shutil.copy2(binary, stage / 'corpstex')
    for source, name in [(ROOT / 'LICENSE', 'LICENSE'), (ROOT / 'NOTICE', 'NOTICE'),
                         (ROOT / 'src/assets/providers/LICENSE', 'PROVIDER-LICENSE')]:
        shutil.copy2(source, stage / name)
    (stage / 'INSTALL.txt').write_text(
        'CorpsTex ' + release_version + '\n\n'
        'Install Codex or OpenCode separately and authenticate using that runtime.\n'
        'CorpsTex does not install runtimes or collect provider keys.\n'
        'Linux: run ./corpstex in a graphical session with GTK3 and WebKitGTK 4.1.\n'
        'For Arch, the .pkg.tar.zst installs with sudo pacman -U FILE.\n'
        'To upgrade: save editor changes, finish/stop turns and close CorpsTex first.\n'
        'Replace the entire portable folder, or install the newer package.\n'
        'History and credentials remain owned by the installed runtime.\n'
        'Unsaved editor buffers and live diagnostics do not survive exit.\n'
        'Source and release limitations: https://github.com/M0KA907/CorpsTex\n', encoding='utf-8')
    with tarfile.open(str(stage) + '.tar.gz', 'x:gz') as archive_file:
        archive_file.add(stage, arcname=stage.name)
    # Arch's binary package format: .PKGINFO plus the installed filesystem tree.
    package = destination / ('corpstex-' + release_version + '-1-x86_64.pkg.tar')
    tree = destination / ('arch-' + release_version)
    tree.mkdir(exist_ok=False)
    paths = [(stage / 'corpstex', 'usr/bin/corpstex'),
             (ROOT / 'src-tauri/icons/icon.png', 'usr/share/icons/hicolor/32x32/apps/corpstex.png')]
    paths.extend((stage / name, 'usr/share/licenses/corpstex/' + name) for name in ['LICENSE', 'NOTICE', 'PROVIDER-LICENSE'])
    for source, target in paths:
        path = tree / target
        path.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, path)
    desktop = tree / 'usr/share/applications/io.github.m0ka907.corpstex.desktop'
    desktop.parent.mkdir(parents=True, exist_ok=True)
    desktop.write_text('[Desktop Entry]\nType=Application\nName=CorpsTex\nExec=corpstex\nIcon=corpstex\nTerminal=false\nCategories=Development;\n', encoding='utf-8')
    size = sum(p.stat().st_size for p in tree.rglob('*') if p.is_file())
    (tree / '.PKGINFO').write_text(
        'pkgname = corpstex\npkgbase = corpstex\npkgver = ' + release_version + '-1\n'
        'pkgdesc = Desktop client for system-installed Codex and OpenCode\n'
        'url = https://github.com/M0KA907/CorpsTex\n'
        'builddate = ' + str(int(time.time())) + '\nsize = ' + str(size) + '\n'
        'arch = x86_64\nlicense = GPL-3.0-only\n'
        'depend = glibc\ndepend = gcc-libs\ndepend = gtk3\ndepend = webkit2gtk-4.1\ndepend = hicolor-icon-theme\n', encoding='utf-8')
    with tarfile.open(package, 'x', format=tarfile.GNU_FORMAT) as archive_file:
        for path in sorted(tree.rglob('*')):
            info = archive_file.gettarinfo(path, arcname=path.relative_to(tree).as_posix())
            info.uid = info.gid = 0
            info.uname = info.gname = 'root'
            if path.is_file():
                with path.open('rb') as handle:
                    archive_file.addfile(info, handle)
            else:
                archive_file.addfile(info)
    subprocess.run(['zstd', '--rm', str(package)], check=True)
    for path in sorted(destination.iterdir()):
        if path.is_file():
            print(hashlib.sha256(path.read_bytes()).hexdigest(), path.name)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['version', 'notices', 'archive'])
    parser.add_argument('--binary', type=Path)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    if args.command == 'version':
        print(version())
    elif args.command == 'notices':
        notices()
    else:
        if not all([args.binary, args.output]):
            parser.error('archive requires --binary and --output')
        archive(args.binary, args.output)
